// Stylist and Outfit domain types for MyStyle AI

import { WardrobeItem } from './wardrobe';

export interface ScoreBreakdown {
  colour: number;
  style: number;
  occasion: number;
  preference: number;
  weather: number;
  formality: number;
  freshness: number;
}

export interface RecommendedOutfit {
  id: string;
  title: string;
  description?: string;
  item_ids: string[];
  items: WardrobeItem[];
  occasion: string;
  style_tags: string[];
  overall_score: number;
  score_breakdown: ScoreBreakdown;
  styling_reason: string;
  styling_tips: string[];
  weather_notes: string;
  /** Short "why it works" chips generated by AI or rule engine */
  why_chips: string[];
  /** Whether an AI provider enhanced this outfit's explanation */
  ai_enhanced: boolean;
  /** Which provider produced the explanation ('gemini'|'groq'|'ollama'|'rule-based') */
  provider_used: string;
  is_favourite?: boolean;
  wear_count?: number;
  last_worn_at?: string;
  created_at?: string;
}

export interface StylistRequest {
  occasion?: string;
  style_preference?: string;
  weather?: string;
  temperature_celsius?: number;
  colour_direction?: string;
  formality_level?: 'Relaxed' | 'Balanced' | 'Polished';
  pinned_item_ids?: string[];
  excluded_item_ids?: string[];
  quantity?: number;
  additional_instructions?: string;
}

export interface OutfitCollection {
  id: string;
  name: string;
  description?: string;
  outfit_ids: string[];
  created_at: string;
}

export interface OutfitPlan {
  id: string;
  planned_date: string;
  outfit_id: string;
  outfit?: RecommendedOutfit;
  occasion: string;
  notes?: string;
  status: 'Planned' | 'Completed' | 'Cancelled';
  created_at: string;
}

export interface StyleProfile {
  style_tags: string[];
  favourite_colours: string[];
  avoided_colours: string[];
  preferred_fits: string[];
  preferred_occasions: string[];
  climate_preference: string;
  comfort_preference: string;
  optional_body_notes?: string;
}
